def render_q1() -> None:
    """Render Problem 1 metrics, adjusted effects, prediction, and interpretation."""
    st.subheader("Problem 1 · Temporal Behavior & Next-Match Performance")
    st.caption(
        "Question: how are recent volume, session depth, and post-loss requeue timing "
        "associated with performance in the following Ranked Solo/Duo match?"
    )

    key_path = Q1_TABLES / "key_results_for_report.csv"
    effects_path = Q1_TABLES / "behavior_effects.csv"
    if not file_ready(key_path) or not file_ready(effects_path):
        missing_results_message("Problem 1", "python code/run_project.py q1 --strict-reference")
        return

    key = read_csv(key_path)
    effects = read_csv(effects_path)

    combined_auc = key_metric(key, "Combined tree test ROC-AUC")
    history_auc = key_metric(key, "History tree test ROC-AUC")
    delta_auc = key_metric(key, "Combined - history AUC")
    holm_terms = key_metric(key, "Holm-significant robustness terms")

    cols = st.columns(4)
    cols[0].metric("Primary targets", format_integer(key_metric(key, "Primary target observations") or 0))
    cols[1].metric("Combined test AUC", format_decimal(combined_auc or np.nan))
    cols[2].metric(
        "Behavioral AUC gain",
        f"+{format_decimal(delta_auc or 0)}",
        help="Combined-tree ROC-AUC minus history-only tree ROC-AUC.",
    )
    cols[3].metric("Holm-significant robustness terms", format_integer(holm_terms or 0))

    st.info(
        "Main message: the data do not support a simple universal story that deeper "
        "sessions or very fast post-loss requeues reliably reduce next-match win probability."
    )

    controls = st.columns([1, 1, 2])
    hypothesis = controls[0].selectbox(
        "Behavioral question",
        ["Session depth", "Post-loss requeue", "Recent ranked volume"],
        key="q1_hypothesis",
    )
    region = controls[1].selectbox(
        "Region",
        ["ALL", "NA", "KR", "EU"],
        key="q1_region",
    )

    primary = primary_effects(effects, hypothesis)
    if primary.empty:
        st.warning("Primary adjusted coefficients were not found in behavior_effects.csv.")
    else:
        st.plotly_chart(
            q1_effect_figure(primary, hypothesis, region),
            use_container_width=True,
            config={"displayModeBar": False},
        )

    left, right = st.columns([1.05, 0.95])
    with left:
        prediction_figure = Q1_FIGURES / "figure_3_prediction_evaluation.png"
        if file_ready(prediction_figure):
            st.image(
                report_image_bytes(prediction_figure),
                caption="Held-out prediction: ROC curves and combined-tree confusion matrix.",
                use_container_width=True,
            )
        else:
            st.markdown("##### Predictive result")
            st.metric("History-only AUC", format_decimal(history_auc or np.nan))
            st.metric("Combined AUC", format_decimal(combined_auc or np.nan))
    with right:
        st.markdown("##### Why this matters")
        st.markdown(
            """
            - Predictors were built **strictly before the target match** to avoid leakage.
            - The main inferential comparison is **within player**, reducing confounding by stable player skill.
            - Uncertainty was clustered by both **player** and **physical match**.
            - The result is **observational**, so it should not be interpreted as a causal test of psychological tilt or fatigue.
            """
        )


def render_q2() -> None:
    """Render the interactive champion-pair explorer for Problem 2."""
    st.subheader("Problem 2 · Champion Pairings & Combo Performance")
    st.caption(
        "Raw popularity, above-expected co-selection, and descriptive pair performance "
        "are deliberately treated as separate quantities."
    )

    pair_path = Q2_TABLES / "pair_stats.csv"
    champion_path = Q2_TABLES / "champion_stats.csv"
    if not file_ready(pair_path) or not file_ready(champion_path):
        missing_results_message("Problem 2", "python code/run_project.py q2")
        return

    pairs = read_csv(pair_path)
    champions = read_csv(champion_path)
    names = champions.sort_values("appearances", ascending=False)["champion_name"].dropna().tolist()

    selected = st.selectbox(
        "Select a champion",
        names,
        index=0,
        key="q2_champion",
    )
    champion_row = champions[champions["champion_name"] == selected].iloc[0]
    selected_pairs = pairs_for_champion(pairs, selected)

    supported = selected_pairs[selected_pairs["games_together"] >= MIN_PAIR_GAMES]
    high_support = selected_pairs[selected_pairs["games_together"] >= MIN_PERFORMANCE_GAMES]

    cols = st.columns(4)
    cols[0].metric("Appearances", f"{int(champion_row['appearances']):,}")
    cols[1].metric("Pick rate", f"{100 * float(champion_row['pick_rate']):.2f}%")
    cols[2].metric("Win rate", f"{100 * float(champion_row['win_rate']):.2f}%")
    cols[3].metric("Supported partners", f"{len(supported):,}")

    if supported.empty:
        st.info(f"No {selected} pairings meet the {MIN_PAIR_GAMES:,}-game support threshold.")
        return

    strongest = supported.nlargest(1, "association").iloc[0]
    common = selected_pairs.nlargest(1, "games_together").iloc[0]
    performance = (
        high_support.nlargest(1, "win_surplus_pp").iloc[0]
        if not high_support.empty
        else None
    )

    highlights = st.columns(3)
    highlights[0].metric(
        "Most common partner",
        common["partner"],
        f"{int(common['games_together']):,} games",
    )
    highlights[1].metric(
        "Strongest normalized partner",
        strongest["partner"],
        f"log₂(lift) {float(strongest['association']):.2f}",
    )
    if performance is not None:
        highlights[2].metric(
            "Largest high-support win surplus",
            performance["partner"],
            f"{float(performance['win_surplus_pp']):+.2f} pp",
        )

    st.plotly_chart(
        q2_scatter(selected_pairs, selected),
        use_container_width=True,
        config={"displayModeBar": False},
    )

    sort_label = st.radio(
        "Rank partner table by",
        ["Normalized association", "Games together", "Win surplus"],
        horizontal=True,
        key="q2_sort",
    )
    sort_map = {
        "Normalized association": "association",
        "Games together": "games_together",
        "Win surplus": "win_surplus_pp",
    }
    table = selected_pairs.sort_values(sort_map[sort_label], ascending=False).head(20)
    table = table[
        [
            "partner",
            "games_together",
            "association",
            "pair_win_rate",
            "win_surplus_pp",
        ]
    ].rename(
        columns={
            "partner": "Partner",
            "games_together": "Games together",
            "association": "log₂(lift)",
            "pair_win_rate": "Pair win rate",
            "win_surplus_pp": "Win surplus (pp)",
        }
    )
    st.dataframe(
        table.style.format(
            {
                "Games together": "{:,.0f}",
                "log₂(lift)": "{:.3f}",
                "Pair win rate": "{:.3f}",
                "Win surplus (pp)": "{:+.3f}",
            }
        ),
        use_container_width=True,
        hide_index=True,
    )

    st.info(
        "Interpretation: a high log₂(lift) means a pair appears together more often "
        "than expected from their individual popularity. Win surplus is descriptive, "
        "not a causal estimate of champion synergy."
    )


