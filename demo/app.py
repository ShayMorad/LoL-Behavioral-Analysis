def pairs_for_champion(pairs: pd.DataFrame, champion: str) -> pd.DataFrame:
    """Return all pair rows involving one champion with a unified partner column."""
    mask = (pairs["champion_a"] == champion) | (pairs["champion_b"] == champion)
    out = pairs.loc[mask].copy()
    out["partner"] = np.where(
        out["champion_a"] == champion,
        out["champion_b"],
        out["champion_a"],
    )
    return out


def primary_effects(effects: pd.DataFrame, hypothesis: str) -> pd.DataFrame:
    """Select the primary adjusted coefficient family for one Q1 hypothesis."""
    settings = {
        "Session depth": ("H1_session_depth", "30m_session_boundary"),
        "Post-loss requeue": ("H2_post_loss_requeue", "categorical_requeue_gap"),
        "Recent ranked volume": ("H3_recent_volume", "6h_window"),
    }
    internal_hypothesis, setting = settings[hypothesis]
    return effects[
        (effects["hypothesis"] == internal_hypothesis)
        & (effects["specification"] == "adjusted")
        & (effects["parameter_setting"] == setting)
    ].copy()


def q1_effect_figure(data: pd.DataFrame, hypothesis: str, region: str) -> go.Figure:
    """Build an interactive coefficient-and-confidence-interval view for Q1."""
    sub = data if region == "ALL" else data[data["source"] == region]
    fig = go.Figure()

    for source in ["NA", "KR", "EU"]:
        current = sub[sub["source"] == source].copy()
        if current.empty:
            continue
        current["label"] = current["term"].map(clean_effect_term)
        current = current.sort_values("estimate_percentage_points")

        estimate = current["estimate_percentage_points"].astype(float)
        low = current["ci_low_percentage_points"].astype(float)
        high = current["ci_high_percentage_points"].astype(float)

        fig.add_trace(
            go.Scatter(
                x=estimate,
                y=current["label"],
                mode="markers",
                name=source,
                marker=dict(size=9, color=REGION_COLORS[source]),
                error_x=dict(
                    type="data",
                    symmetric=False,
                    array=(high - estimate),
                    arrayminus=(estimate - low),
                    thickness=1.4,
                ),
                customdata=np.column_stack(
                    [
                        current["p_value_holm"].astype(float),
                        current["reference_category"].astype(str),
                    ]
                ),
                hovertemplate=(
                    "<b>%{y}</b><br>"
                    "Effect: %{x:.3f} pp<br>"
                    "Holm p: %{customdata[0]:.4g}<br>"
                    "Reference: %{customdata[1]}<extra>%{fullData.name}</extra>"
                ),
            )
        )

    fig.add_vline(x=0, line_dash="dash", line_color="#AAB5BF")
    fig.update_layout(
        title=f"{hypothesis}: adjusted within-player effects",
        xaxis_title="Change in next-match win probability (percentage points)",
        yaxis_title="",
    )
    return style_plot(fig, height=500)


