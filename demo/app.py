        hover_data={
            "games_together": ":,",
            "pair_win_rate": ":.3f",
            "association": ":.3f",
            "win_surplus_pp": ":.3f",
        },
        size_max=34,
        color="games_together",
        color_continuous_scale=["#37506A", "#C89B3C", "#F4D98A"],
