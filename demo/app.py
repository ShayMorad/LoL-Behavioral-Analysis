@st.cache_data(show_spinner=False)
def read_csv(path: Path) -> pd.DataFrame:
    """Load one generated CSV while preserving the literal region label "NA"."""
    # Pandas treats the string "NA" as missing by default; preserving it fixes
    # the empty North-America plots in the Problem 1 region selector.
    return pd.read_csv(path, keep_default_na=False, na_values=[""])


@st.cache_data(show_spinner=False)
def report_image_bytes(path: Path, background: str = "#F7F3E8") -> bytes:
    """Flatten a transparent report PNG onto a light background for readability."""
    with Image.open(path) as image:
        rgba = image.convert("RGBA")
        bg = Image.new("RGBA", rgba.size, background)
        bg.alpha_composite(rgba)
        flattened = bg.convert("RGB")

        buffer = io.BytesIO()
        flattened.save(buffer, format="PNG")
        return buffer.getvalue()


@st.cache_data(show_spinner=False)
def read_json(path: Path) -> dict:
    """Load one generated JSON summary and cache it for the current session."""
    return json.loads(path.read_text(encoding="utf-8"))


def file_ready(path: Path) -> bool:
    """Return whether a required generated output currently exists."""
    return path.exists() and path.is_file()


def format_integer(value: float | int) -> str:
    """Format whole-number metrics with thousands separators."""
    return f"{int(round(float(value))):,}"


def format_decimal(value: float, digits: int = 4) -> str:
    """Format a numeric result consistently for metric cards."""
    return f"{float(value):.{digits}f}"


def key_metric(table: pd.DataFrame, name: str) -> float | None:
    """Read one named metric from Q1's compact key-results table."""
    if table.empty or "metric" not in table or "value" not in table:
        return None
    rows = table.loc[table["metric"] == name, "value"]
    return None if rows.empty else float(rows.iloc[0])


def clean_effect_term(term: str) -> str:
    """Convert internal regression term names into short presentation labels."""
    text = str(term)
    replacements = {
        "session_depth_": "Session game ",
        "post_loss_gap_": "Gap ",
        "recent_games_": "Recent games ",
    }
    for prefix, replacement in replacements.items():
        if text.startswith(prefix):
            return text.replace(prefix, replacement, 1)
    return text.replace("_", " ").title()


def style_plot(fig: go.Figure, *, height: int = 470) -> go.Figure:
    """Apply one consistent dark navy/gold visual style to interactive charts."""
    fig.update_layout(
        template="plotly_dark",
        height=height,
        margin=dict(l=20, r=20, t=55, b=20),
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(8,22,36,0.35)",
        font=dict(color="#E8EDF2"),
        title_font=dict(color="#F5E6C8"),
        legend_title_text="",
    )
    return fig


